"""The fly pursuit circuit exported to C (fly_pursuit_all.h) and the parts of the firmware module
that can run on the laptop (flyPursuitCore.h), plus the script that patches OpenCatEsp32."""

import importlib.util
import shutil
import subprocess
from pathlib import Path

import pytest
from flybrain_edge.export.equivalence import find_cc
from flybrain_edge.export.pursuit_c import build_pursuit, cost, export, render
from flybrain_edge.export.pursuit_equivalence import build_library, compare

ROOT = Path(__file__).resolve().parents[3]
MODULE = ROOT / "firmware" / "bittle" / "fly_pursuit"
FIRMWARE = MODULE / "src"
needs_cc = pytest.mark.skipif(find_cc() is None, reason="no C compiler (cc/gcc/clang) on PATH")
needs_cxx = pytest.mark.skipif(shutil.which("c++") is None, reason="no C++ compiler (c++) on PATH")

# Largest accepted difference between the C (float32) and Python (float64) turn commands. The
# measured difference is about 1e-3 rad/s (0.06 deg/s) against turns of up to 8 rad/s; the head
# is limited to 60 deg/s (1.05 rad/s), so 5e-3 rad/s (0.3 deg/s) is far below anything visible.
TURN_TOL_RAD_S = 5e-3


def test_compact_layout_and_sizes():
    px = build_pursuit()
    assert px.meta["n_full"] == 265
    assert px.n == 264 and px.meta["dropped_neurons"] == ["LC10a"]  # no path to DNa02
    assert int(px.cnt.max()) <= 255 and len(px.lc_idx) == 231
    c = cost(px)
    assert c["flash_data_bytes"] < 0.8 * c["float32_csr_bytes_for_comparison"]
    assert c["flash_data_bytes"] < 9000 and c["state_ram_bytes"] < 4200
    text = render(px)
    assert "malloc" not in text and "static inline float fp_step" in text
    assert "static const uint8_t FP_CNT" in text and "fp_dna02_left" in text


@needs_cc
def test_header_compiles_warning_free(tmp_path):
    assert build_library(tmp_path).exists()


@needs_cc
def test_c_matches_python_closed_loop_and_steering_curve():
    r = compare(every=4)  # 29 of the 114 benchmark episodes, about 3,000 frames
    assert r["frames"] > 2000
    assert r["max_abs_turn_diff_rad_s"] < TURN_TOL_RAD_S, r
    assert r["closed_loop_max_bearing_diff_deg"] < 0.1, r
    assert r["steering_curve_max_abs_diff_rad_s"] < TURN_TOL_RAD_S, r
    assert r["steering_curve_peak_turn_rad_s"] > 1.0  # the curve is not trivially flat


def test_firmware_header_is_current(tmp_path):
    export(tmp_path)
    strip = lambda s: "\n".join(ln for ln in s.splitlines() if "generated by" not in ln)
    shipped = (FIRMWARE / "fly_pursuit_all.h").read_text()
    assert strip(shipped) == strip((tmp_path / "fly_pursuit_all.h").read_text()), (
        "regenerate with flybrain-export pursuit --single-header"
    )


@needs_cxx
def test_module_core_against_host(tmp_path):
    exe = tmp_path / "core"
    subprocess.run(
        [
            "c++",
            "-std=c++11",
            "-Wall",
            "-Wextra",
            "-Werror",
            "-I",
            str(FIRMWARE),
            "-o",
            str(exe),
            str(Path(__file__).with_name("export_stubs") / "pursuit_core_main.cpp"),
        ],
        check=True,
        capture_output=True,
        text=True,
    )
    out = subprocess.run([str(exe)], capture_output=True, text=True, check=False)
    assert out.returncode == 0, out.stdout + out.stderr



import shutil
import subprocess
from pathlib import Path

import pytest
from flybrain_edge.export import build_model, render
from flybrain_edge.export.equivalence import build_harness, compare, find_cc

ROOT = Path(__file__).resolve().parents[3]
FIRMWARE = ROOT / "firmware" / "bittle" / "fly_escape" / "src"
needs_cc = pytest.mark.skipif(find_cc() is None, reason="no C compiler (cc/gcc/clang) on PATH")
needs_cxx = pytest.mark.skipif(shutil.which("c++") is None, reason="no C++ compiler (c++) on PATH")


def test_render_is_self_contained():
    h, c, single = render(build_model())
    assert "malloc" not in c and "calloc" not in c
    assert "static const float FE_VAL[2212]" in c
    assert "fe_step" in h and "fe_calibrate" in h
    assert "static inline" in single and '#include "fly_escape.h"' not in single


def test_compact_layout_is_lossless_and_small():
    from flybrain_edge.export.escape_c_compact import build_compact, cost_compact

    full = build_compact(prune=False)
    slim = build_compact()
    assert slim.meta["dropped_neurons"] == ["DNp02", "DNp11", "AMMC-A1"]
    assert slim.n == 348 and full.n == 351
    assert int(slim.cnt.max()) <= 255 and len(slim.cls_scale) < 16
    assert cost_compact(slim)["flash_data_bytes"] < 0.5 * 16068  # the float32 layout


LAYOUTS = ["compact", "compact-full", "full"]


@needs_cc
@pytest.mark.parametrize("layout", LAYOUTS)
def test_c_compiles_warning_free(tmp_path, layout):
    assert build_harness(tmp_path, layout=layout).exists()


@needs_cc
@pytest.mark.parametrize("layout", LAYOUTS)
def test_c_matches_python_tick_by_tick(layout):
    res = compare(sim_every=8, layout=layout)  # both real recordings + 48 simulated episodes
    for name in ("connectome", "looming_rate_threshold"):
        r = res[name]
        assert r["python_triggers"] > 20
        assert r["trigger_tick_mismatches"] == 0, r
        assert r["side_mismatches_on_triggers"] == 0, r
        assert r["max_abs_drive_diff"] < 1e-4, r
    assert res["connectome"]["max_abs_gf_diff"] < 1e-4


def test_firmware_header_is_current(tmp_path):
    from flybrain_edge.export import export

    export(tmp_path, single_header_only=True)
    shipped = (FIRMWARE / "fly_escape_all.h").read_text()
    fresh = (tmp_path / "fly_escape_all.h").read_text()
    strip = lambda s: "\n".join(ln for ln in s.splitlines() if "generated by" not in ln)
    assert strip(shipped) == strip(fresh), "regenerate with flybrain-export --single-header"


@needs_cxx
def test_firmware_module_against_host_stubs(tmp_path):
    stubs = Path(__file__).with_name("export_stubs")
    exe = tmp_path / "module"
    subprocess.run(
        [
            "c++",
            "-std=c++11",
            "-Wall",
            "-Wextra",
            "-Werror",
            "-I",
            str(stubs),
            "-I",
            str(FIRMWARE),
            "-o",
            str(exe),
            str(stubs / "module_main.cpp"),
        ],
        check=True,
        capture_output=True,
        text=True,
    )
    out = subprocess.run([str(exe)], capture_output=True, text=True, check=False)
    assert out.returncode == 0, out.stdout + out.stderr

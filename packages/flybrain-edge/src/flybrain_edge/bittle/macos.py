"""Run a Bluetooth command on macOS through a tiny helper app, so macOS can ask for permission.

Why: macOS only lets a process use Bluetooth if the *app responsible for it* declares
NSBluetoothAlwaysUsageDescription in its Info.plist. A command started from Terminal.app (or
the Claude app) is attributed to that app, which declares nothing, so the process is killed the
moment bleak touches CoreBluetooth (exit 134, "TCC ... NSBluetoothAlwaysUsageDescription").

The fix is a minimal app bundle that declares Bluetooth use and whose executable is a shell
script that runs the real command. Started with `open`, the bundle becomes the responsible app;
macOS shows its normal Bluetooth consent prompt for it once, and remembers the answer. Nothing
here bypasses that prompt.

    flybrain-bittle macos-ble-app            # create/refresh the helper, print how to use it
    flybrain-bittle ble-run -- <command...>  # run a command through it, output in this terminal

`ble-run` launches `open -W -n --stdout F --stderr F2 FlybrainBLE.app --args <workdir> <state>
<PATH> <command...>`, prints the two log files as they grow, forwards Ctrl-C to the command
(so a robot is still put to rest), and exits with the command's exit code.
"""

from __future__ import annotations

import os
import plistlib
import shlex
import shutil
import signal
import subprocess
import sys
import tempfile
import time
from pathlib import Path

BUNDLE_ID = "com.neuraffica.flybrain.blerunner"
BUNDLE_NAME = "FlybrainBLE.app"
EXEC_NAME = "flybrain-ble-run"
USAGE_TEXT = (
    "flybrain uses Bluetooth to talk to a Petoi robot dog (Bittle). This helper only runs the "
    "flybrain command you started from the terminal."
)
ENV_MARK = "FLYBRAIN_BLE_BUNDLE"  # set by the helper script for the command it runs
ENV_NO_HINT = "FLYBRAIN_BLE_NO_HINT"

SCRIPT = r"""#!/bin/bash
# Generated by `flybrain-bittle macos-ble-app` (package flybrain-edge). Runs ONE command with
# this bundle as the responsible app, so macOS asks for Bluetooth permission for the bundle.
# Arguments (passed by `open ... --args`): <workdir> <statedir> <PATH> <command...>
# Writes <statedir>/pid (process group of the command) and <statedir>/exit (its exit code).
if [ "$#" -lt 4 ]; then
  echo "usage: $0 <workdir> <statedir> <PATH> <command...>" >&2
  exit 64
fi
workdir="$1"; state="$2"; export PATH="$3"; shift 3
export FLYBRAIN_BLE_BUNDLE=1 PYTHONUNBUFFERED=1
mkdir -p "$state"
if ! cd "$workdir"; then
  echo "flybrain BLE helper: cannot cd to $workdir" >&2
  echo 66 > "$state/exit"
  exit 66
fi
set -m                      # the command gets its own process group
"$@" &
child=$!
echo "$child" > "$state/pid"
trap 'kill -INT -- "-$child" 2>/dev/null' INT
trap 'kill -TERM -- "-$child" 2>/dev/null' TERM
code=0
while :; do
  wait "$child"; code=$?
  kill -0 "$child" 2>/dev/null || break   # a trap interrupted wait: keep waiting
done
echo "$code" > "$state/exit"
exit "$code"
"""


def default_dir() -> Path:
    return Path.home() / "Library" / "Application Support" / "flybrain"


def info_plist() -> dict:
    return {
        "CFBundleIdentifier": BUNDLE_ID,
        "CFBundleName": "Flybrain BLE",
        "CFBundleDisplayName": "Flybrain BLE",
        "CFBundleExecutable": EXEC_NAME,
        "CFBundlePackageType": "APPL",
        "CFBundleShortVersionString": "1.0",
        "CFBundleVersion": "1",
        "CFBundleInfoDictionaryVersion": "6.0",
        "LSUIElement": True,  # no Dock icon, no menu bar
        "LSMinimumSystemVersion": "11.0",
        "NSBluetoothAlwaysUsageDescription": USAGE_TEXT,
    }


def build_bundle(directory: str | Path | None = None) -> Path:
    """Create (or refresh) FlybrainBLE.app in ``directory``; return the bundle path."""
    app = Path(directory or default_dir()).expanduser() / BUNDLE_NAME
    macos = app / "Contents" / "MacOS"
    macos.mkdir(parents=True, exist_ok=True)
    with open(app / "Contents" / "Info.plist", "wb") as f:
        plistlib.dump(info_plist(), f)
    exe = macos / EXEC_NAME
    exe.write_text(SCRIPT)
    exe.chmod(0o755)
    return app


def resolve_command(argv: list[str], path: str | None = None) -> list[str]:
    """Absolute program path: under `open` the command does not inherit this shell's PATH."""
    if not argv:
        raise ValueError("no command given")
    prog = argv[0]
    if os.sep not in prog:
        found = shutil.which(prog, path=path)
        if found is None:
            raise FileNotFoundError(f"{prog!r} not found on PATH")
        prog = found
    return [prog, *argv[1:]]


def open_command(
    app: Path, argv: list[str], workdir: str | Path, state: str | Path, path: str
) -> list[str]:
    """The `open` invocation that runs ``argv`` through the helper bundle."""
    state = Path(state)
    return [
        "open",
        "-W",  # wait until the app (and so the command) exits
        "-n",  # a new instance each time
        "--stdout",
        str(state / "stdout.log"),
        "--stderr",
        str(state / "stderr.log"),
        str(app),
        "--args",
        str(workdir),
        str(state),
        path,
        *argv,
    ]


def suggested_command(argv: list[str] | None = None) -> str:
    """How to rerun the current command through the helper."""
    argv = list(sys.argv if argv is None else argv)
    prog = os.path.basename(argv[0]) if argv else "flybrain-bittle"
    if prog.endswith(".py") or prog in ("python", "python3", "__main__.py"):
        inner = [sys.executable, *argv]
    else:
        inner = ["uv", "run", prog, *argv[1:]]
    return "uv run flybrain-bittle ble-run -- " + shlex.join(inner)


def warn_if_ble_will_be_killed(stream=None) -> bool:
    """On macOS, outside the helper, explain the exit-134 kill before bleak is imported.

    The usage description that matters belongs to the app that launched this process (Terminal,
    an IDE), which Python cannot inspect reliably, so the hint is printed whenever this process
    was not started by the helper. Returns True if it printed. Set FLYBRAIN_BLE_NO_HINT=1 to
    silence it (e.g. in a terminal app that declares Bluetooth use)."""
    if sys.platform != "darwin" or os.environ.get(ENV_MARK) == "1" or os.environ.get(ENV_NO_HINT):
        return False
    out = stream or sys.stderr
    print(
        "flybrain: Bluetooth on macOS needs an app that declares Bluetooth use. Commands "
        "started from Terminal or the Claude app are usually killed by macOS at this point "
        "(exit code 134, nothing else printed). If that happens, run the same command through "
        "the flybrain helper app, which makes macOS ask you for Bluetooth permission once:\n"
        f"    {suggested_command()}\n"
        "(set FLYBRAIN_BLE_NO_HINT=1 to hide this message)",
        file=out,
        flush=True,
    )
    return True


def _pump(src: Path, pos: int, dst) -> int:
    try:
        with open(src, "rb") as f:
            f.seek(pos)
            data = f.read()
    except FileNotFoundError:
        return pos
    if data:
        dst.buffer.write(data) if hasattr(dst, "buffer") else dst.write(
            data.decode(errors="replace")
        )
        dst.flush()
    return pos + len(data)


def _forward(state: Path, sig: int) -> bool:
    try:
        pid = int((state / "pid").read_text().strip())
    except (FileNotFoundError, ValueError):
        return False
    try:
        os.killpg(pid, sig)  # the helper started the command in its own process group
    except ProcessLookupError:
        return False
    except PermissionError:
        os.kill(pid, sig)
    return True


def ble_run(
    argv: list[str], directory: str | Path | None = None, workdir: str | None = None
) -> int:
    """Run ``argv`` through the helper bundle and relay its output; returns its exit code."""
    if sys.platform != "darwin":
        print(
            "flybrain: ble-run is only needed on macOS; running the command directly.",
            file=sys.stderr,
        )
        return subprocess.call(argv)
    path = os.environ.get("PATH", "/usr/bin:/bin")
    cmd = resolve_command(argv, path)
    app = build_bundle(directory)
    state = Path(tempfile.mkdtemp(prefix="flybrain-ble-"))
    for name in ("stdout.log", "stderr.log"):
        (state / name).touch()
    launch = open_command(app, cmd, workdir or os.getcwd(), state, path)
    print(
        f"flybrain: running through {app} (macOS may ask for Bluetooth permission)",
        file=sys.stderr,
        flush=True,
    )
    # own session: Ctrl-C in this terminal must reach us (and be forwarded to the command),
    # not kill `open -W`, which would leave the command running unattended
    proc = subprocess.Popen(launch, start_new_session=True)
    pos_out = pos_err = 0
    interrupts = 0
    while True:
        try:
            done = proc.poll() is not None
            pos_out = _pump(state / "stdout.log", pos_out, sys.stdout)
            pos_err = _pump(state / "stderr.log", pos_err, sys.stderr)
            if done:
                break
            time.sleep(0.1)
        except KeyboardInterrupt:
            interrupts += 1
            sig = signal.SIGINT if interrupts < 3 else signal.SIGTERM
            if not _forward(state, sig):
                proc.terminate()
    try:
        return int((state / "exit").read_text().strip())
    except (FileNotFoundError, ValueError):
        return proc.returncode or 1

"""Generate a self-contained C99 implementation of the fly escape model.

The output is two files, ``fly_escape.h`` and ``fly_escape.c``:

* the shipped connectome model (``flybrain_models.escape.EscapeCircuit`` with the
  ``connectome`` scalars): sparse (CSR) float32 weights with the fitted gains folded in,
  per-neuron biases, the input populations, the time constant, input gain, the two
  giant-fiber thresholds, refractory period and side margin;
* the looming-rate baseline (``LoomingRateThreshold``) behind the same API;
* the raw-ADC -> proximity mapping with per-channel baseline calibration and the deadband.

No dynamic allocation; all data is ``static const`` (flash on the ESP32); the only libm
calls are ``expf`` (once per step) and ``tanhf`` (once per neuron with positive input per
sub-step), both provided by the ESP32 Arduino core's newlib.

float32 rather than fixed point: the ESP32 has a single-precision FPU, so float32 costs no
more than int32 multiply-adds, and the measured deviation from the float64 Python model is
far below anything that changes a trigger (see the equivalence test).
"""

from __future__ import annotations

import datetime as _dt
from dataclasses import dataclass
from pathlib import Path

import numpy as np

PREFIX = "fe"  # C symbol prefix


@dataclass
class ExportedModel:
    n: int
    row_ptr: np.ndarray  # (n+1,) uint16
    col_idx: np.ndarray  # (nnz,) uint16
    val: np.ndarray  # (nnz,) float32
    bias: np.ndarray  # (n,) float32
    lplc2_l: np.ndarray
    lplc2_r: np.ndarray
    lc4_l: np.ndarray
    lc4_r: np.ndarray
    gf: tuple[int, int]
    tau: float
    k_in: float
    dt_sub: float
    th_l: float
    th_r: float
    refractory_s: float
    side_margin: float
    v_ref: float
    deadband: float
    baseline: float
    loom_threshold: float
    meta: dict


def build_model(params_key: str = "connectome") -> ExportedModel:
    from flybrain_models import escape as esc

    m = esc.EscapeCircuit.from_pack("escape", params=params_key)
    W = m._W
    n = W.shape[0]
    rows, cols = np.nonzero(W)
    order = np.lexsort((cols, rows))
    rows, cols = rows[order], cols[order]
    row_ptr = np.zeros(n + 1, dtype=np.int64)
    np.add.at(row_ptr, rows + 1, 1)
    row_ptr = np.cumsum(row_ptr)
    p = m.params
    loom = esc.load_params("looming_rate_threshold")["threshold"]
    return ExportedModel(
        n=n,
        row_ptr=row_ptr.astype(np.uint16),
        col_idx=cols.astype(np.uint16),
        val=W[rows, cols].astype(np.float32),
        bias=m._bias.astype(np.float32),
        lplc2_l=m._lplc2["L"],
        lplc2_r=m._lplc2["R"],
        lc4_l=m._lc4["L"],
        lc4_r=m._lc4["R"],
        gf=(int(m._gf[0]), int(m._gf[1])),
        tau=m.tau,
        k_in=m.k_in,
        dt_sub=m.dt_sub,
        th_l=m.gf_thresholds[0],
        th_r=m.gf_thresholds[1],
        refractory_s=float(p.get("refractory_s", esc.REFRACTORY_S)),
        side_margin=esc.SIDE_MARGIN,
        v_ref=esc.V_REF,
        deadband=esc.DEADBAND_RAW,
        baseline=esc.BASELINE_RAW,
        loom_threshold=float(loom),
        meta={
            "params_key": params_key,
            "date": _dt.date.today().isoformat(),
            "pack": "escape (FlyWire v783, CC BY 4.0)",
        },
    )


def _c_array(ctype: str, name: str, values, per_line: int = 12, fmt=str) -> str:
    vals = [fmt(v) for v in values]
    lines = [", ".join(vals[i : i + per_line]) for i in range(0, len(vals), per_line)]
    body = ",\n    ".join(lines)
    return f"static const {ctype} {name}[{len(vals)}] = {{\n    {body}\n}};\n"


def _f32(x) -> str:
    s = f"{float(np.float32(x)):.9g}"
    if "e" not in s and "." not in s and "inf" not in s and "nan" not in s:
        s += ".0"
    return s + "f"


HEADER = """\
/* fly_escape.h - generated by flybrain-export ({date}); do not edit by hand.
 *
 * Fly looming-escape circuit (FlyWire v783 connectome: LC4, LPLC2 -> giant fibers) on a
 * two-channel IR proximity sensor, plus the looming-rate baseline behind the same API.
 * Connectome data: Dorkenwald et al. 2024; Schlegel et al. 2024 (Nature), CC BY 4.0.
 *
 * Usage (both models):
 *   fe_state_t s; fe_init(&s, FE_MODEL_CONNECTOME);   // or FE_MODEL_LOOMING
 *   fe_calibrate(&s, raw_l, raw_r, n);                // empty-scene samples, both channels
 *   fe_result_t r = fe_step(&s, raw_l, raw_r, dt_ms); // every 25-90 ms (validated range)
 *   if (r.trigger) ...; r.side: +1 left, -1 right, 0 centre/unknown
 */
#ifndef FLY_ESCAPE_H
#define FLY_ESCAPE_H

#include <stdint.h>

#ifdef __cplusplus
extern "C" {{
#endif

#define FE_N_NEURONS {n}
#define FE_MODEL_CONNECTOME 0
#define FE_MODEL_LOOMING 1

typedef struct {{
  uint8_t model;
  float baseline_l, baseline_r; /* empty-scene raw reading per channel */
  float r[FE_N_NEURONS];        /* firing rates (connectome model) */
  float prev_l, prev_r;         /* previous proximity */
  uint8_t has_prev;
  uint8_t above;                /* drive was above threshold on the previous step */
  float since_trigger_s;        /* time since the last trigger */
  float gf_l, gf_r;             /* giant-fiber rates (connectome) or proximity rates (looming) */
  float drive;                  /* decision variable; triggers when it crosses 1 */
}} fe_state_t;

typedef struct {{
  uint8_t trigger; /* 1 on the step an escape is commanded (debounced, refractory) */
  int8_t side;     /* +1 robot's left, -1 right, 0 centre/unknown */
  float drive;     /* decision variable, threshold is 1 */
}} fe_result_t;

void fe_init(fe_state_t *s, uint8_t model);
void fe_reset(fe_state_t *s);
/* Set the empty-scene baselines from n samples per channel (mean). n == 0 keeps the default. */
void fe_calibrate(fe_state_t *s, const uint16_t *raw_l, const uint16_t *raw_r, uint16_t n);
void fe_set_baseline(fe_state_t *s, float baseline_l, float baseline_r);
float fe_raw_to_proximity(float raw, float baseline);
fe_result_t fe_step(fe_state_t *s, float raw_l, float raw_r, float dt_ms);

#ifdef __cplusplus
}}
#endif

#endif /* FLY_ESCAPE_H */
"""

SOURCE = """\
/* fly_escape.c - generated by flybrain-export ({date}); do not edit by hand.
 * Model: flybrain_models.escape.EscapeCircuit, params "{params_key}", pack {pack}.
 * {n} neurons, {nnz} nonzero weights (CSR, float32, fitted gains folded in).
 */
{include}
#include <math.h>
#include <stddef.h>

#define FE_NNZ {nnz}
static const float FE_TAU = {tau};
static const float FE_K_IN = {k_in};
static const float FE_DT_SUB = {dt_sub};
static const float FE_TH_L = {th_l};
static const float FE_TH_R = {th_r};
static const float FE_REFRACTORY_S = {refractory_s};
static const float FE_SIDE_MARGIN = {side_margin};
static const float FE_V_REF = {v_ref};
static const float FE_DEADBAND = {deadband};
static const float FE_DEFAULT_BASELINE = {baseline};
static const float FE_LOOM_THRESHOLD = {loom_threshold};
static const uint16_t FE_GF_L = {gf_l};
static const uint16_t FE_GF_R = {gf_r};

{arrays}
FE_API float fe_raw_to_proximity(float raw, float baseline) {{
  float top = baseline - FE_DEADBAND;
  float p;
  if (top <= 0.0f) return 0.0f;
  p = (top - raw) / top;
  if (p < 0.0f) p = 0.0f;
  if (p > 1.0f) p = 1.0f;
  return p;
}}

FE_API void fe_reset(fe_state_t *s) {{
  uint16_t i;
  for (i = 0; i < FE_N_NEURONS; i++) s->r[i] = 0.0f;
  s->prev_l = s->prev_r = 0.0f;
  s->has_prev = 0;
  s->above = 0;
  s->since_trigger_s = 1.0e9f;
  s->gf_l = s->gf_r = 0.0f;
  s->drive = 0.0f;
}}

FE_API void fe_init(fe_state_t *s, uint8_t model) {{
  s->model = model;
  s->baseline_l = s->baseline_r = FE_DEFAULT_BASELINE;
  fe_reset(s);
}}

FE_API void fe_set_baseline(fe_state_t *s, float baseline_l, float baseline_r) {{
  s->baseline_l = baseline_l;
  s->baseline_r = baseline_r;
}}

FE_API void fe_calibrate(fe_state_t *s, const uint16_t *raw_l, const uint16_t *raw_r, uint16_t n) {{
  uint32_t sl = 0, sr = 0;
  uint16_t i;
  if (n == 0) return;
  for (i = 0; i < n; i++) {{
    sl += raw_l[i];
    sr += raw_r[i];
  }}
  s->baseline_l = (float)sl / (float)n;
  s->baseline_r = (float)sr / (float)n;
}}

static int8_t fe_side(float left, float right) {{
  float big = left > right ? left : right;
  float diff = left - right;
  if (diff < 0.0f) diff = -diff;
  if (big <= 0.0f || diff <= FE_SIDE_MARGIN * big) return 0;
  return left > right ? 1 : -1;
}}

static uint8_t fe_trigger(fe_state_t *s, float dt) {{
  uint8_t above = s->drive >= 1.0f;
  uint8_t fire;
  s->since_trigger_s += dt;
  fire = above && !s->above && s->since_trigger_s >= FE_REFRACTORY_S;
  s->above = above;
  if (fire) s->since_trigger_s = 0.0f;
  return fire;
}}

static float fe_mean(const float *r, const uint16_t *idx, uint16_t n) {{
  float acc = 0.0f;
  uint16_t i;
  for (i = 0; i < n; i++) acc += r[idx[i]];
  return acc / (float)n;
}}

/* One exponential-Euler sub-step: r += a * (tanh(max(0, W r + drive)) - r).
 * u is computed for all rows from the old r before any r is updated. */
static void fe_substep(float *r, const float *drive, float a, float *u) {{
  uint16_t i, k;
  for (i = 0; i < FE_N_NEURONS; i++) {{
    float acc = drive[i];
    for (k = FE_ROW_PTR[i]; k < FE_ROW_PTR[i + 1]; k++) acc += FE_VAL[k] * r[FE_COL_IDX[k]];
    u[i] = acc;
  }}
  for (i = 0; i < FE_N_NEURONS; i++) {{
    float t = u[i] > 0.0f ? tanhf(u[i]) : 0.0f; /* tanh(0) == 0: skip the call */
    r[i] += a * (t - r[i]);
  }}
}}

FE_API fe_result_t fe_step(fe_state_t *s, float raw_l, float raw_r, float dt_ms) {{
  fe_result_t out;
  float dt = dt_ms * 0.001f;
  float pl = fe_raw_to_proximity(raw_l, s->baseline_l);
  float pr = fe_raw_to_proximity(raw_r, s->baseline_r);
  float vl = 0.0f, vr = 0.0f;
  if (s->has_prev && dt > 0.0f) {{
    vl = (pl - s->prev_l) / dt;
    vr = (pr - s->prev_r) / dt;
    if (vl < 0.0f) vl = 0.0f;
    if (vr < 0.0f) vr = 0.0f;
  }}
  s->prev_l = pl;
  s->prev_r = pr;
  s->has_prev = 1;

  if (s->model == FE_MODEL_LOOMING) {{
    s->gf_l = vl;
    s->gf_r = vr;
    s->drive = (vl > vr ? vl : vr) / FE_LOOM_THRESHOLD;
    out.trigger = fe_trigger(s, dt);
    out.side = fe_side(pl, pr); /* the nearer channel */
    out.drive = s->drive;
    return out;
  }}

  {{
    static float drive_in[FE_N_NEURONS]; /* scratch (not part of the model state) */
    static float u[FE_N_NEURONS];
    uint16_t i;
    for (i = 0; i < FE_N_NEURONS; i++) drive_in[i] = FE_BIAS[i];
    for (i = 0; i < FE_N_LPLC2_L; i++) drive_in[FE_LPLC2_L[i]] += FE_K_IN * pl;
    for (i = 0; i < FE_N_LPLC2_R; i++) drive_in[FE_LPLC2_R[i]] += FE_K_IN * pr;
    for (i = 0; i < FE_N_LC4_L; i++) drive_in[FE_LC4_L[i]] += FE_K_IN * vl / FE_V_REF;
    for (i = 0; i < FE_N_LC4_R; i++) drive_in[FE_LC4_R[i]] += FE_K_IN * vr / FE_V_REF;
    if (dt > 0.0f) {{
      uint16_t n_sub = (uint16_t)ceilf(dt / FE_DT_SUB - 1e-6f);
      float a;
      if (n_sub < 1) n_sub = 1;
      a = 1.0f - expf(-(dt / (float)n_sub) / FE_TAU);
      for (i = 0; i < n_sub; i++) fe_substep(s->r, drive_in, a, u);
    }}
  }}
  s->gf_l = s->r[FE_GF_L];
  s->gf_r = s->r[FE_GF_R];
  {{
    float dl = s->gf_l / FE_TH_L, dr = s->gf_r / FE_TH_R;
    s->drive = dl > dr ? dl : dr;
  }}
  out.trigger = fe_trigger(s, dt);
  out.side = fe_side(fe_mean(s->r, FE_LC4_L, FE_N_LC4_L) + fe_mean(s->r, FE_LPLC2_L, FE_N_LPLC2_L),
                     fe_mean(s->r, FE_LC4_R, FE_N_LC4_R) + fe_mean(s->r, FE_LPLC2_R, FE_N_LPLC2_R));
  out.drive = s->drive;
  return out;
}}
"""


def render(model: ExportedModel) -> tuple[str, str, str]:
    arrays = []
    arrays.append(_c_array("uint16_t", "FE_ROW_PTR", model.row_ptr.tolist(), 16))
    arrays.append(_c_array("uint16_t", "FE_COL_IDX", model.col_idx.tolist(), 16))
    arrays.append(_c_array("float", "FE_VAL", model.val.tolist(), 8, _f32))
    arrays.append(_c_array("float", "FE_BIAS", model.bias.tolist(), 8, _f32))
    for name, idx in (
        ("LPLC2_L", model.lplc2_l),
        ("LPLC2_R", model.lplc2_r),
        ("LC4_L", model.lc4_l),
        ("LC4_R", model.lc4_r),
    ):
        arrays.append(f"#define FE_N_{name} {len(idx)}\n")
        arrays.append(_c_array("uint16_t", f"FE_{name}", [int(i) for i in idx], 16))
    fields = {
        "date": model.meta["date"],
        "params_key": model.meta["params_key"],
        "pack": model.meta["pack"],
        "n": model.n,
        "nnz": len(model.val),
        "tau": _f32(model.tau),
        "k_in": _f32(model.k_in),
        "dt_sub": _f32(model.dt_sub),
        "th_l": _f32(model.th_l),
        "th_r": _f32(model.th_r),
        "refractory_s": _f32(model.refractory_s),
        "side_margin": _f32(model.side_margin),
        "v_ref": _f32(model.v_ref),
        "deadband": _f32(model.deadband),
        "baseline": _f32(model.baseline),
        "loom_threshold": _f32(model.loom_threshold),
        "gf_l": model.gf[0],
        "gf_r": model.gf[1],
        "arrays": "\n".join(arrays),
    }
    header = HEADER.format(**fields)
    source = SOURCE.format(include='#include "fly_escape.h"\n#define FE_API', **fields)
    # single-header variant for Arduino sketches whose src/ is header-only (OpenCatEsp32):
    # the same code with every function static inline
    types = header.split("void fe_init(")[0]
    single = (
        types.replace("fly_escape.h - generated", "fly_escape_all.h - generated").replace(
            "FLY_ESCAPE_H", "FLY_ESCAPE_ALL_H"
        )
        + "#ifdef __cplusplus\n}\n#endif\n\n"
        + SOURCE.format(include="#define FE_API static inline", **fields)
        + "\n#endif /* FLY_ESCAPE_ALL_H */\n"
    )
    return header, source, single


def export(
    out_dir: str | Path, params_key: str = "connectome", single_header_only: bool = False
) -> dict:
    """Write fly_escape.h + fly_escape.c (library) and fly_escape_all.h (single header, all
    functions static inline, for Arduino sketches); only the latter if single_header_only."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    model = build_model(params_key)
    h, c, single = render(model)
    files = ["fly_escape_all.h"]
    (out / "fly_escape_all.h").write_text(single)
    if not single_header_only:
        (out / "fly_escape.h").write_text(h)
        (out / "fly_escape.c").write_text(c)
        files = ["fly_escape.h", "fly_escape.c", *files]
    return {"dir": str(out), "n": model.n, "nnz": len(model.val), "files": files, **cost(model)}


def cost(model: ExportedModel) -> dict:
    """Static sizes (bytes) of the exported data and the state."""
    n, nnz = model.n, len(model.val)
    idx = sum(len(x) for x in (model.lplc2_l, model.lplc2_r, model.lc4_l, model.lc4_r))
    return {
        "flash_data_bytes": 2 * (n + 1) + 2 * nnz + 4 * nnz + 4 * n + 2 * idx + 15 * 4,
        "state_ram_bytes": 4 * n + 4 * 11,  # fe_state_t, roughly
        "scratch_ram_bytes": 2 * 4 * n,  # drive_in and u (static)
        "macs_per_substep": nnz,
    }

"""`flydeck install-app`: build Flydeck.app, a real macOS app for this checkout.

The app is a stay-open AppleScript applet (made with the system's ``osacompile``, so it has a
proper Dock icon, name and Quit menu) whose Info.plist declares Bluetooth use. On launch it runs
``Contents/Resources/flydeck-launch.sh start``, which starts the hub with this checkout's Python
in the background and opens the page. Everything the hub starts (demos, robot checks) descends
from the app, so macOS asks for Bluetooth permission once, for "Flydeck", and remembers it.

Quitting the app (Dock, Cmd-Q) asks the hub to stop any demo, which rests the robot. If the app
is force-quit, the hub notices its parent is gone and does the same.

The checkout and Python paths are written into the launcher at install time. If the checkout
moves, the app shows a dialog saying how to reinstall it.
"""

from __future__ import annotations

import datetime as dt
import json
import plistlib
import shlex
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from .icon import icns_bytes

APP_NAME = "Flydeck"
BUNDLE_ID = "com.neuraffica.flydeck"
LAUNCHER = "flydeck-launch.sh"
ICON = "flydeck"
USAGE_TEXT = (
    "Flydeck uses Bluetooth to find and talk to your Petoi robot (Bittle) and to run the "
    "flybrain demos on it."
)

APPLESCRIPT = r"""-- Flydeck: starts the flybrain demo hub of one checkout (see Resources/flydeck-launch.sh)
on launcherPath()
	return quoted form of (POSIX path of (path to me) & "Contents/Resources/flydeck-launch.sh")
end launcherPath

on startHub()
	try
		do shell script launcherPath() & " start $PPID"
	on error errMsg
		display alert "Flydeck cannot start" message errMsg as critical buttons {"Quit"} default button 1
		quit
	end try
end startHub

on run
	startHub()
end run

on reopen
	startHub()
end reopen

on idle
	try
		do shell script launcherPath() & " alive"
	on error
		quit
	end try
	return 3
end idle

on quit
	try
		do shell script launcherPath() & " stop"
	end try
	continue quit
end quit
"""

LAUNCH_SH = r"""#!/bin/bash
# Generated by `uv run flydeck install-app` on {date}. Do not edit: reinstall instead.
# start <app pid> | alive | stop
CHECKOUT={checkout}
PYTHON={python}
STATE="$HOME/Library/Application Support/flybrain"
LOG="$HOME/Library/Logs/Flydeck.log"
URLFILE="$STATE/flydeck.url"
PIDFILE="$STATE/flydeck.pid"
export PATH="/usr/bin:/bin:/usr/sbin:/sbin:$PATH"
OPEN="${{FLYDECK_OPEN_CMD:-open}}"  # tests replace it so no browser opens

alive() {{ [ -s "$PIDFILE" ] && kill -0 "$(cat "$PIDFILE")" 2>/dev/null; }}

case "$1" in
start)
  if [ ! -d "$CHECKOUT" ] || [ ! -x "$PYTHON" ]; then
    echo "Flydeck was installed from $CHECKOUT, which has moved or has no Python environment any more. Open Terminal in your flybrain folder and run: uv sync && uv run flydeck install-app" >&2
    exit 1
  fi
  if alive && [ -s "$URLFILE" ]; then $OPEN "$(cat "$URLFILE")"; exit 0; fi
  mkdir -p "$STATE" "$(dirname "$LOG")"
  rm -f "$URLFILE"
  cd "$CHECKOUT" || exit 1
  echo "--- Flydeck starting $(date)" >>"$LOG"
  FLYDECK_APP=1 FLYBRAIN_BLE_BUNDLE=1 PYTHONUNBUFFERED=1 nohup "$PYTHON" -m flydeck \
    --app --no-open --parent-pid "${{2:-0}}" --url-file "$URLFILE" >>"$LOG" 2>&1 </dev/null &
  echo $! >"$PIDFILE"
  for _ in $(seq 1 150); do
    if [ -s "$URLFILE" ]; then $OPEN "$(cat "$URLFILE")"; exit 0; fi
    if ! alive; then
      echo "Flydeck stopped while starting. Last lines of $LOG:" >&2
      tail -n 6 "$LOG" >&2
      exit 1
    fi
    sleep 0.2
  done
  echo "Flydeck did not start within 30 s. See $LOG" >&2
  exit 1
  ;;
alive)
  alive
  ;;
stop)
  alive || exit 0
  pid="$(cat "$PIDFILE")"
  if [ -s "$URLFILE" ]; then
    curl -s -m 3 -X POST -H 'Content-Type: application/json' -d '{{}}' \
      "$(cat "$URLFILE")api/quit" >/dev/null 2>&1
  else
    kill -INT "$pid" 2>/dev/null
  fi
  # the hub stops a running demo (the robot rests) before it exits: give it time
  for _ in $(seq 1 175); do kill -0 "$pid" 2>/dev/null || exit 0; sleep 0.2; done
  kill -TERM "$pid" 2>/dev/null
  exit 0
  ;;
*)
  echo "usage: $0 start <pid> | alive | stop" >&2
  exit 64
  ;;
esac
"""


def default_dir() -> Path:
    return Path.home() / "Applications"


def info_updates() -> dict:
    return {
        "CFBundleIdentifier": BUNDLE_ID,
        "CFBundleName": APP_NAME,
        "CFBundleDisplayName": APP_NAME,
        "CFBundleIconFile": ICON,
        "CFBundleShortVersionString": "0.1.0",
        "CFBundleVersion": "1",
        "LSMinimumSystemVersion": "11.0",
        "NSBluetoothAlwaysUsageDescription": USAGE_TEXT,
        "NSHumanReadableCopyright": "flybrain starter kit",
    }


def launcher_text(checkout: Path, python: str) -> str:
    return LAUNCH_SH.format(
        date=dt.datetime.now().strftime("%Y-%m-%d %H:%M"),
        checkout=shlex.quote(str(checkout)),
        python=shlex.quote(python),
    )


def build_app(
    checkout: Path,
    python: str | None = None,
    directory: Path | None = None,
    sign: bool = True,
) -> Path:
    """Create (or replace) Flydeck.app; return its path. macOS only (needs osacompile)."""
    if sys.platform != "darwin" or shutil.which("osacompile") is None:
        raise RuntimeError("install-app makes a macOS app; it needs macOS (osacompile)")
    python = python or sys.executable
    target_dir = Path(directory or default_dir()).expanduser()
    target_dir.mkdir(parents=True, exist_ok=True)
    app = target_dir / f"{APP_NAME}.app"
    with tempfile.TemporaryDirectory() as tmp:
        src = Path(tmp) / "flydeck.applescript"
        src.write_text(APPLESCRIPT)
        built = Path(tmp) / f"{APP_NAME}.app"
        subprocess.run(
            ["osacompile", "-s", "-o", str(built), str(src)],
            check=True,
            capture_output=True,
        )
        res = built / "Contents" / "Resources"
        for stale in ("applet.icns", "Assets.car"):
            (res / stale).unlink(missing_ok=True)
        (res / f"{ICON}.icns").write_bytes(icns_bytes())
        launcher = res / LAUNCHER
        launcher.write_text(launcher_text(checkout, python))
        launcher.chmod(0o755)
        (res / "flydeck-install.json").write_text(
            json.dumps(
                {
                    "checkout": str(checkout),
                    "python": python,
                    "installed": dt.datetime.now().isoformat(),
                },
                indent=2,
            )
        )
        plist_path = built / "Contents" / "Info.plist"
        with open(plist_path, "rb") as f:
            info = plistlib.load(f)
        info.pop("CFBundleIconName", None)
        for key in [k for k in info if k.endswith("UsageDescription")]:
            info.pop(key)  # osacompile's generic texts: Flydeck asks for Bluetooth only
        info.update(info_updates())
        with open(plist_path, "wb") as f:
            plistlib.dump(info, f)
        if sign and shutil.which("codesign"):
            # the plist changed: re-sign ad hoc so macOS accepts the bundle as one unit
            subprocess.run(
                ["codesign", "--force", "--deep", "--sign", "-", str(built)],
                check=True,
                capture_output=True,
            )
        if app.exists():
            shutil.rmtree(app)
        shutil.move(str(built), str(app))
    lsregister = Path(
        "/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework"
        "/Support/lsregister"
    )
    if lsregister.exists():  # refresh the Dock/Finder icon cache; harmless if it fails
        subprocess.run([str(lsregister), "-f", str(app)], check=False, capture_output=True)
    return app
